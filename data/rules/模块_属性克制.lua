    local function groupByCoef(results, n)
        local groups = {} -- key: coef(number), value: 列表
        for _, r in ipairs(results) do
            local coef = tonumber(r.coef) -- 强制转数字
            if not coef then
                coef = 1
            end -- 兜底
            local g = groups[coef] or {}
            if #g < n then
                g[#g + 1] = r
                groups[coef] = g
            end
        end

        -- 收集所有系数并降序
        local coefs = {}
        for coef in pairs(groups) do
            coefs[#coefs + 1] = coef
        end
        table.sort(coefs, function(a, b)
            return a > b
        end)

        -- 按系数顺序展平
        local out = {}
        for _, coef in ipairs(coefs) do
            for _, r in ipairs(groups[coef]) do
                out[#out + 1] = r
            end
        end
        return out
    end
    -- 排序
    -- 排序 attackResults (将 nil 视为 0)
table.sort(attackResults, function(a, b)
    return (a.coef or 0) > (b.coef or 0)
end)

-- 排序 defenseResults (将 nil 视为 0)
