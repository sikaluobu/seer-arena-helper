-- 去重函数
local function unique(t)
    local seen, out = {}, {}
    for _, v in ipairs(t) do
        if not seen[v] then
            seen[v] = true
            table.insert(out, v)
        end
    end
    for i, v in ipairs(out) do
        t[i] = v
    end
    for i = #out + 1, #t do
        t[i] = nil
    end -- 把多余尾巴清掉
end

