-- 工具：分割属性
local function splitAttribute(attr)
    if string.find(attr, "·") then
        local parts = {}
        for part in string.gmatch(attr, "([^·]+)") do
            table.insert(parts, part)
        end
        return parts
    else
        return {attr}
    end
end

-- 双属性系数计算
-- 返回单属性 atkAttr 对 defAttr 的系数（缺省=1）
local singleCallCount = 0 -- Add counter variable inside the module scope (or as a local within singleCoef if you reset it each top-level call)
function p.singleCoef(atkAttr, defAttr, mode)
    singleCallCount = singleCallCount + 1
    p.debugInfo["sc_call_" .. singleCallCount .. "_atk"] = atkAttr -- Store the atkAttr for this call
    p.debugInfo["sc_call_" .. singleCallCount .. "_def"] = defAttr -- Store defAttr (optional)
    p.debugInfo["sc_call_" .. singleCallCount .. "_mode"] = mode -- Store mode (optional)

    -- (保留原有的 singleCoef 逻辑不变)
    if string.find(atkAttr, "·") then
        local A, B = atkAttr:match("([^·]+)·([^·]+)")
        -- mw.log("拆半：" .. atkAttr .. " → " .. A .. " + " .. B) -- Comment out old log if you want to avoid confusion
        local a = p.singleCoef(A, defAttr, mode)
        local b = p.singleCoef(B, defAttr, mode)
        if a == 2 and b == 2 then
            return 4
        end
        if a == 0 or b == 0 then
            return (a + b) / 4
        end
        return (a + b) / 2
    end

    local t = p.coefData[atkAttr]
    if not t then
        -- Keep the original log or modify it to also use debugInfo if needed
        mw.log("缺失单属性表：" .. atkAttr) -- This will still show up potentially somewhere else
        -- Also store in debug info that an error occurred for this attr
        p.debugInfo["sc_error_for_atk_attr"] = atkAttr
        return 1
    end
    local v = t[mode][defAttr]
    if v == nil then
        mw.log("缺失系数：" .. atkAttr .. " " .. mode .. " → " .. defAttr)
        return 1
    end
    return v
end

--[[
  计算 双属性 A·B 对 单属性 C 的系数
  符合官方规则：
    两个系数都是 2 → 4
    任一系数为 0 → (和)/4
    其余           → (和)/2
]]
function p.dualVsSingle(A, B, C, mode)
    p.debugInfo.dvs_A = A -- Store A
    p.debugInfo.dvs_B = B -- Store B
    p.debugInfo.dvs_C = C -- Store C (optional but good for context)
    p.debugInfo.dvs_mode = mode -- Store mode (optional)

    local a = p.singleCoef(A, C, mode)
    local b = p.singleCoef(B, C, mode)
    -- ... (rest of the original dualVsSingle logic)
    if a == 2 and b == 2 then
        return 4
    end
    if a == 0 or b == 0 then
        return (a + b) / 4
    end
    return (a + b) / 2
end

-- 主入口：计算 dualAttr 对 targetAttr 的系数
-- mode = "attack" / "defense"
function p.getDualAttributeCoef(dualAttr, targetAttr, mode)
    -- 检查 dualAttr 是否为双属性
    -- Use plain find to avoid pattern matching issues
    local isDual = string.find(dualAttr, "·", 1, true) ~= nil

    if isDual then
        -- dualAttr 是双属性，按原来逻辑处理
        local A, B = dualAttr:match("([^·]+)·([^·]+)")
        -- *** 添加修正逻辑 ***
        if A == "沌" then
            A = "混沌"
        end
        if B == "沌" then
            B = "混沌"
        end
        if A == "圣" then -- Also add correction for "圣"
            A = "圣灵"
        end
        if B == "圣" then
            B = "圣灵"
        end

        -- Manually split targetAttr to avoid relying on potentially broken splitAttribute
        local tPos = string.find(targetAttr, "·", 1, true) -- Try plain search first
        local tParts
        if tPos then
            tParts = { string.sub(targetAttr, 1, tPos - 1), string.sub(targetAttr, tPos + 2) } -- +2 for UTF-8 "·"
        else
            tParts = { targetAttr }
        end

        if #tParts == 1 then
            -- 双 vs 单
            return p.dualVsSingle(A, B, tParts[1], mode)
        else
            -- 双 vs 双：分别计算 双→t1 和 双→t2 两个中间值，再平均
            local x = p.dualVsSingle(A, B, tParts[1], mode)
            local y = p.dualVsSingle(A, B, tParts[2], mode)
            return (x + y) / 2
        end
    else
        -- dualAttr 是单属性 (isDual 为 false)，targetAttr 是双属性
        -- 这对应于 "单 vs 双" 的情况，例如 "轮回" vs "混沌·圣灵"
        -- 需要调用不同的逻辑：将双属性拆开，分别计算单 vs 单，然后合并
        local sParts = { dualAttr } -- dualAttr is single, so parts is just { dualAttr }

        -- Manually split targetAttr (the double attribute) using byte-level operations
        local attr_str = targetAttr
        local len = #attr_str
        local separator_bytes = { 0xC2, 0xB7 } -- UTF-8 bytes for "·" (MIDDLE DOT)
        local sep_len = 2 -- "·" is 2 bytes
        local found_pos = nil

        -- Search for the separator bytes
        for i = 1, len - sep_len + 1 do
            if string.byte(attr_str, i) == separator_bytes[1] and
               string.byte(attr_str, i+1) == separator_bytes[2] then
                found_pos = i
                break
            end
        end

        local tParts
        if found_pos then
            -- Reconstruct substrings byte by byte
            local part1_bytes = {}
            for i = 1, found_pos - 1 do
                table.insert(part1_bytes, string.byte(attr_str, i))
            end
            local part1 = ""
            for _, b in ipairs(part1_bytes) do
                part1 = part1 .. string.char(b)
            end

            local part2_bytes = {}
            for i = found_pos + sep_len, len do -- Start after the separator (skip 2 bytes)
                table.insert(part2_bytes, string.byte(attr_str, i))
            end
            local part2 = ""
            for _, b in ipairs(part2_bytes) do
                part2 = part2 .. string.char(b)
            end

            tParts = { part1, part2 }
        else
            tParts = { attr_str } -- Fallback if "·" not found
        end

        if #tParts == 1 then
            -- 单 vs 单
            return p.singleCoef(sParts[1], tParts[1], mode)
        else
            -- 单 vs 双：计算 单→t1 和 单→t2 两个中间值，再合并
            local c1 = p.singleCoef(sParts[1], tParts[1], mode) -- 例如 "虚空" vs "混沌"
            local c2 = p.singleCoef(sParts[1], tParts[2], mode) -- 例如 "虚空" vs "圣灵"
            if c1 == 2 and c2 == 2 then
                return 4
            elseif c1 == 0 or c2 == 0 then
                return (c1 + c2) / 4
            else
                return (c1 + c2) / 2
            end
        end
    end
end

