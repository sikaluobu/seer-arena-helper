        for _, r in ipairs(results) do
            local img = p.getImagePath(r.attr)
local cls = ""
local coef_value = r.coef or 0 -- 将 nil 视为 0
if coef_value > 2 then
    cls = "coef-2"
elseif coef_value > 1 then
    cls = "coef-1"
elseif coef_value == 1 then
    cls = "coef-1-1"
elseif coef_value < 1 and coef_value > 0 then
    cls = "coef-less-1"
elseif coef_value == 0 then -- 这也涵盖了原来 coef 为 nil 的情况
    cls = "coef-0"
end
            table.insert(html, string.format(
    [[<div class="shuxing" style="display: inline-block;background: #36c;overflow: hidden;position:relative;width: 50px;height: 71px;box-shadow: 0 0 2px #000;margin:2px;border-radius: 4px;"><div class="shuxingi" style="margin-left: 11px;margin-top: 8px;">%s</div><div class="%s" style="position: absolute;bottom: -2px;left:0px;font-size:12px;color:#fff;font-weight: bolder;text-shadow: #000 -1px 0 0,#763c12 0 -1px 0,#5d2b08 1px 0 0,#1d1515 0 1px 0;width: 50px;display: inline-block;overflow: hidden;white-space: nowrap;text-overflow: ellipsis;line-height:14px;padding:2px 0px;"><center><b color="#fff">%.4g</b></center></div></div>]],
    img, cls, r.coef or 0)) -- <- 直接处理 nil
        end
        table.insert(html, "</div>")
        return table.concat(html, "\n")
    end

